"""Compile the independently authored Vulkan test shaders to embedded SPIR-V."""
import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SHADERS = ROOT / "port/linux/src/vulkan/tests"


def generate(compiler):
    text = ["/* Generated by tools/vulkan_shaders.py; do not edit. */", "#include <stdint.h>"]
    with tempfile.TemporaryDirectory(prefix="gulch-vulkan-shaders-") as directory:
        for stage in ("vert", "frag"):
            source = SHADERS / ("depth." + stage)
            output = Path(directory) / (stage + ".spv")
            subprocess.run([compiler, "-V", "--target-env", "vulkan1.1", "-o", str(output), str(source)], check=True)
            data = output.read_bytes()
            words = struct.unpack("<" + "I" * (len(data) // 4), data)
            assert words[0] == 0x07230203
            digest = hashlib.sha256(source.read_bytes()).hexdigest()
            text += [f"/* depth.{stage} SHA256: {digest} */", f"static const uint32_t depth_{stage}[] = {{"]
            for index in range(0, len(words), 8):
                text.append("\t" + ", ".join(f"0x{word:08x}" for word in words[index:index + 8]) + ",")
            text.append("};")
    (SHADERS / "depth_spirv.h").write_text("\n".join(text) + "\n", encoding="ascii", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", default="glslangValidator")
    generate(parser.parse_args().compiler)
